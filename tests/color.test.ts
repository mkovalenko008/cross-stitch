describe('CIEDE2000', () => {
  it.each(SHARMA.map((row, i) => [i + 1, row]))('пара %i из Sharma et al.', (_, row) => {
    const [L1, a1, b1, L2, a2, b2, expected] = row as number[];
    expect(ciede2000(L1, a1, b1, L2, a2, b2)).toBeCloseTo(expected, 4);
  });

  it('симметрична', () => {
    for (const [L1, a1, b1, L2, a2, b2] of SHARMA) {
      expect(ciede2000(L1, a1, b1, L2, a2, b2)).toBeCloseTo(ciede2000(L2, a2, b2, L1, a1, b1), 10);
    }
  });

  it('равна нулю для одинаковых цветов', () => {
    expect(ciede2000(40, 20, -30, 40, 20, -30)).toBe(0);
  });

  it('нижняя граница по светлоте не превышает ΔE00', () => {
    let seed = 7;
    const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);
    for (let i = 0; i < 20000; i++) {
      const p = [rnd() * 100, rnd() * 200 - 100, rnd() * 200 - 100, rnd() * 100, rnd() * 200 - 100, rnd() * 200 - 100];
      expect(lightnessLowerBound(p[0], p[3])).toBeLessThanOrEqual(ciede2000(p[0], p[1], p[2], p[3], p[4], p[5]) + 1e-9);
    }
  });
});

describe('sRGB → Lab (D65)', () => {
  // Эталонные значения для sRGB/D65 (калькулятор Bruce Lindbloom, те же матрицы).
  const cases: [number[], number[]][] = [
    [[0, 0, 0], [0, 0, 0]],
    [[255, 255, 255], [100, 0, 0]],
    [[255, 0, 0], [53.2408, 80.0925, 67.2032]],
    [[0, 255, 0], [87.7347, -86.1827, 83.1793]],
    [[0, 0, 255], [32.297, 79.1875, -107.8602]],
    [[128, 128, 128], [53.585, 0, 0]],
  ];
  it.each(cases)('%j', (rgb, lab) => {
    const got = rgb8ToLab(rgb);
    expect(got[0]).toBeCloseTo(lab[0], 2);
    expect(got[1]).toBeCloseTo(lab[1], 2);
    expect(got[2]).toBeCloseTo(lab[2], 2);
  });

  it('линеаризация sRGB обратима', () => {
    for (let i = 0; i < 256; i++) expect(linearToSrgb8(SRGB_TO_LINEAR[i])).toBe(i);
  });

  it('цвет символа: чёрный на светлом, белый на тёмном', () => {
    expect(contrastTextIsBlack([255, 255, 255])).toBe(true);
    expect(contrastTextIsBlack([255, 230, 0])).toBe(true);
    expect(contrastTextIsBlack([0, 0, 0])).toBe(false);
    expect(contrastTextIsBlack([30, 40, 120])).toBe(false);
  });
});
